/// The bug that stayed green for weeks, reproduced against real storage.
///
/// The TypeScript side could not catch it: `mockScripts.list()` implements
/// `filter.view` itself, so the Trash view worked perfectly in every test that
/// fell through to the mock. The Rust side could not catch it either, because
/// nothing sent Rust the frontend's payload. Only this shape can — the exact
/// captured payload, the real command, real rows.
#[test]
fn the_trash_view_payload_actually_selects_trashed_scripts() {
    let fixture = capture_fixture();
    let h = harness();

    let live = h.expect_ok(
        "create_script",
        json!({ "input": { "title": "Still live", "source": "# Live\n" } }),
    );
    let doomed = h.expect_ok(
        "create_script",
        json!({ "input": { "title": "Doomed", "source": "# Doomed\n" } }),
    );
    let doomed_id = doomed["id"].as_str().unwrap().to_string();

    h.expect_ok(
        "trash_script",
        json!({
            "scriptId": doomed_id,
            "expectedRevision": doomed["scriptRevision"].as_i64().unwrap(),
        }),
    );

    // The payload the production `listScripts({ view: 'trash' })` really sends.
    //
    // The page index is forced to Rust's first page. `PageRequest.page` is
    // ZERO-based (`repo.rs`: `offset = page * page_size`) while the captured
    // payload — like the hand-written `script-command-payloads.json` before it
    // — carries `page: 1` for what a UI would call the first page. See
    // `the_first_page_is_page_zero` for the guard on that.
    let mut trash_args = fixture["invocations"]["list_scripts_trash"]["args"].clone();
    trash_args["page"]["page"] = json!(0);
    let page = h.expect_ok("list_scripts", trash_args);
    let titles: Vec<&str> = page["items"]
        .as_array()
        .expect("items")
        .iter()
        .map(|i| i["title"].as_str().unwrap())
        .collect();
    assert_eq!(
        titles,
        vec!["Doomed"],
        "the Trash payload must return the TRASHED script and nothing else; \
         listing live scripts here is the exact defect the mock backend hid"
    );

    // And the All view is its complement, not its superset.
    let mut all_args = fixture["invocations"]["list_scripts_all"]["args"].clone();
    // The captured All payload carries a `query`; drop it so this asserts the
    // status split rather than the search.
    all_args["filter"] = json!({});
    all_args["page"]["page"] = json!(0);
    let page = h.expect_ok("list_scripts", all_args);
    let titles: Vec<&str> = page["items"]
        .as_array()
        .unwrap()
        .iter()
        .map(|i| i["title"].as_str().unwrap())
        .collect();
    assert_eq!(titles, vec!["Still live"]);
    assert_eq!(live["title"], json!("Still live"));
}

/// The full document lifecycle over IPC, using the captured payload shapes.
/// Every step asserts a real state change, so replacing any command body with
/// a constant fails here.
#[test]
fn the_script_lifecycle_round_trips_through_the_real_command_layer() {
    let h = harness();

    let created = h.expect_ok(
        "create_script",
        json!({ "input": { "title": "Keynote", "source": "# Keynote\n\nHello.\n" } }),
    );
    let id = created["id"].as_str().unwrap().to_string();
    let r1 = created["scriptRevision"].as_i64().unwrap();

    // Save advances the revision and persists the new source.
    let saved = h.expect_ok(
        "save_script",
        json!({
            "scriptId": id,
            "expectedRevision": r1,
            "source": "# Keynote\n\nRevised.\n",
            "metadataPatch": { "title": "Keynote II" },
        }),
    );
    let r2 = saved["scriptRevision"].as_i64().unwrap();
    assert!(r2 > r1, "a save must advance the revision: {r1} → {r2}");
    assert!(
        saved["savedAt"].is_string(),
        "the save result must report when it landed, got: {saved}"
    );

    // H1 — the compare-and-swap. Re-sending the stale revision must be REFUSED,
    // not merged. Rust signals this as an error, not as a result status; see
    // `the_save_result_shape_matches_the_typescript_interface`.
    let stale = h
        .invoke(
            "save_script",
            json!({
                "scriptId": id,
                "expectedRevision": r1,
                "source": "# Keynote\n\nClobbered.\n",
                "metadataPatch": {},
            }),
        )
        .expect_err(
            "a save against a stale revision must be refused; without this two \
             windows silently overwrite each other",
        );
    assert_eq!(
        stale["code"],
        json!("SCRIPT_CONFLICT"),
        "the refusal must carry the stable code the frontend switches on, got: {stale}"
    );
    assert_eq!(stale["details"]["actualRevision"], json!(r2));

    // …and the clobbering source really did not land.
    let after = h.expect_ok("list_scripts", json!({ "filter": {} }));
    assert_eq!(after["items"][0]["scriptRevision"], json!(r2));

    // Rename is visible in the listing.
    let renamed = h.expect_ok(
        "rename_script",
        json!({ "scriptId": id, "title": "Renamed", "expectedRevision": r2 }),
    );
    assert_eq!(renamed["title"], json!("Renamed"));

    // Trash → restore → the script is live again.
    let trashed = h.expect_ok(
        "trash_script",
        json!({ "scriptId": id, "expectedRevision": renamed["scriptRevision"].as_i64().unwrap() }),
    );
    assert_eq!(trashed["status"], json!("trash"));
    let restored = h.expect_ok(
        "restore_script",
        json!({ "scriptId": id, "expectedRevision": trashed["scriptRevision"].as_i64().unwrap() }),
    );
    assert_ne!(restored["status"], json!("trash"));

    // Permanent delete really removes it: the next read is an error.
    h.expect_ok(
        "trash_script",
        json!({ "scriptId": id, "expectedRevision": restored["scriptRevision"].as_i64().unwrap() }),
    );
    h.expect_ok("permanently_delete_script", json!({ "scriptId": id }));
    let listed = h.expect_ok("list_scripts", json!({ "filter": { "status": "trash" } }));
    assert_eq!(listed["total"], json!(0));
}

// ---------------------------------------------------------------------------
// 2b. Response-shape drift — the direction the contract tests never covered
// ---------------------------------------------------------------------------

/// Argument drift is only half the boundary. A field the TypeScript side reads
/// off a RESPONSE that Rust does not serialize is `undefined` at runtime, which
/// in JavaScript is not an error — it is a quietly-false branch. And because
/// `mock-backend.ts` provides its own richer response, every test that falls
/// through to the mock sees the field and passes.
///
/// KNOWN_DIVERGENCES is the escape hatch, and each entry is a defect with a
/// reason, not a licence. Deleting an entry is how a fix is proven.
const KNOWN_DIVERGENCES: &[(&str, &str, &str)] = &[(
    "SaveResult",
    "status",
    "DEFECT: src/control/services/scripts-types.ts declares `status: 'saved' | \
     'conflict'` and src/control/stores/editor.ts:137 branches on it, but Rust's \
     SaveResult (src-tauri/src/scripts/mod.rs) has no such field and signals a \
     conflict as an AppError with code SCRIPT_CONFLICT. `result.status` is \
     therefore always undefined against the real backend, the 'conflict' save \
     state is unreachable, and the F.8 conflict resolution sheet in \
     Editor.svelte can never open — the error branch fires instead. \
     mock-backend.ts DOES return { status: 'conflict' }, which is why every \
     frontend test of this path passes. Remove this entry when editor.ts reads \
     the error code instead.",
)];

#[test]
fn the_save_result_shape_matches_the_typescript_interface() {
    let h = harness();
    let created = h.expect_ok(
        "create_script",
        json!({ "input": { "title": "Shape", "source": "# Shape\n" } }),
    );
    let saved = h.expect_ok(
        "save_script",
        json!({
            "scriptId": created["id"].as_str().unwrap(),
            "expectedRevision": created["scriptRevision"].as_i64().unwrap(),
            "source": "# Shape\n\nMore.\n",
            "metadataPatch": {},
        }),
    );
    let actual: BTreeSet<String> = saved
        .as_object()
        .expect("SaveResult is an object")
        .keys()
        .cloned()
        .collect();

    let declared = typescript_interface_fields("scripts-types.ts", "SaveResult");
    assert!(
        !declared.is_empty(),
        "the scan found no fields on the TypeScript `SaveResult`; it has been \
         renamed or moved and this guard has gone vacuous"
    );

    let allowed: BTreeSet<&str> = KNOWN_DIVERGENCES
        .iter()
        .filter(|(interface, ..)| *interface == "SaveResult")
        .map(|(_, field, _)| *field)
        .collect();

    let missing: Vec<&String> = declared
        .iter()
        .filter(|field| !actual.contains(*field) && !allowed.contains(field.as_str()))
        .collect();
    assert!(
        missing.is_empty(),
        "the TypeScript `SaveResult` reads {missing:?}, which the Rust command does \
         not send. Reading an absent field yields `undefined`, which silently takes \
         the false branch. Either fix the contract or add the field to \
         KNOWN_DIVERGENCES with a reason."
    );

    // A divergence that has been FIXED must be removed from the allowlist, or
    // the list becomes a graveyard nobody trusts.
    for (interface, field, _) in KNOWN_DIVERGENCES {
        if *interface != "SaveResult" {
            continue;
        }
        assert!(
            !actual.contains(*field),
            "`SaveResult.{field}` is now sent by Rust — delete its KNOWN_DIVERGENCES \
             entry so the guard covers it"
        );
    }
}

/// Read the field names off a TypeScript `interface X { … }` block. Crude on
/// purpose: it only has to work on the DTO files, and the assertion above fails
/// loudly if it ever matches nothing.
fn typescript_interface_fields(file: &str, interface: &str) -> BTreeSet<String> {
    let source = std::fs::read_to_string(repo_root().join("src/control/services").join(file))
        .unwrap_or_else(|e| panic!("{file}: {e}"));
    let Some(start) = source.find(&format!("interface {interface} {{")) else {
        return BTreeSet::new();
    };
    let body_start = start + source[start..].find('{').expect("open brace") + 1;
    let body_end = body_start + source[body_start..].find('}').expect("close brace");
    source[body_start..body_end]
        .lines()
        .filter_map(|line| {
            let line = line.trim();
            if line.starts_with("//") || line.starts_with('*') || line.starts_with("/*") {
                return None;
            }
            let name = line.split(':').next()?.trim().trim_end_matches('?');
            if name.is_empty() || !name.chars().all(|c| c.is_alphanumeric() || c == '_') {
                return None;
            }
            Some(name.to_string())
        })
        .collect()
}

/// `PageRequest.page` is ZERO-based: `repo::list_scripts` computes
/// `offset = page * page_size`. Both IPC fixtures carry `page: 1` for what a UI
/// would call the first page, and `PageRequest::default()` is page 0 — so the
/// day something actually paginates, a 1-based caller silently skips the first
/// screenful. Nothing in the frontend passes a page today (see
/// `no_typescript_caller_paginates_yet`), which is the only reason this has not
/// shipped as a bug.
#[test]
fn the_first_page_is_page_zero() {
    let h = harness();
    for title in ["Alpha", "Bravo", "Charlie"] {
        h.expect_ok(
            "create_script",
            json!({ "input": { "title": title, "source": format!("# {title}\n") } }),
        );
    }

    let page0 = h.expect_ok(
        "list_scripts",
        json!({ "sort": "name", "page": { "page": 0, "pageSize": 1 } }),
    );
    assert_eq!(page0["items"][0]["title"], json!("Alpha"));
    assert_eq!(page0["total"], json!(3));

    let page1 = h.expect_ok(
        "list_scripts",
        json!({ "sort": "name", "page": { "page": 1, "pageSize": 1 } }),
    );
    assert_eq!(
        page1["items"][0]["title"],
        json!("Bravo"),
        "page 1 is the SECOND page; a caller that treats it as the first sees \
         nothing until the library exceeds one page"
    );

    // The default must be the first page, not an offset into nothing.
    let defaulted = h.expect_ok("list_scripts", json!({ "sort": "name" }));
    assert_eq!(defaulted["items"][0]["title"], json!("Alpha"));
}

/// The other half of the pagination guard: no TypeScript caller passes a page
/// yet. When one appears, this fails and whoever wrote it has to decide which
/// base they meant — which is the moment the ambiguity above becomes a bug.
#[test]
fn no_typescript_caller_paginates_yet() {
    // A constructed `ScriptPageRequest` is the only way to reach the paged
    // path, and `pageSize:` is the token that betrays one.
    let mut declaring = Vec::new();
    let mut constructing = Vec::new();
    for path in walk_sources(&repo_root().join("src")) {
        let source = std::fs::read_to_string(&path).expect("source");
        let is_type_declaration = path.ends_with("services/scripts-types.ts");
        for (index, line) in source.lines().enumerate() {
            let trimmed = line.trim();
            if trimmed.starts_with("//") || trimmed.starts_with('*') {
                continue;
            }
            if !trimmed.contains("pageSize") {
                continue;
            }
            let site = format!("{}:{}", path.display(), index + 1);
            if is_type_declaration {
                declaring.push(site);
            } else {
                constructing.push(site);
            }
        }
    }

    // Guard on the guard: if `pageSize` disappears from the DTO the scan below
    // is looking for a token that no longer exists and can never fire.
    assert!(
        !declaring.is_empty(),
        "the scan found no `pageSize` in src/control/services/scripts-types.ts — \
         the paged DTO was renamed and this guard has gone vacuous"
    );
    assert!(
        constructing.is_empty(),
        "a caller now builds a page request: {constructing:?}. `PageRequest.page` \
         is ZERO-based in Rust (repo.rs: offset = page * page_size) while both IPC \
         fixtures use `page: 1` for the first page. Confirm which base the new \
         caller means before this ships."
    );
}

fn walk_sources(dir: &std::path::Path) -> Vec<std::path::PathBuf> {
    let mut out = Vec::new();
    let Ok(entries) = std::fs::read_dir(dir) else {
        return out;
    };
    for entry in entries.flatten() {
        let path = entry.path();
        if path.is_dir() {
            out.extend(walk_sources(&path));
        } else {
            let name = path.file_name().and_then(|n| n.to_str()).unwrap_or("");
            if (name.ends_with(".ts") || name.ends_with(".svelte")) && !name.ends_with(".test.ts") {
                out.push(path);
            }
        }
    }
    out
}

/// §43.5 / §36 — the session generation the stage never received.
///
/// `AppCoordinator::begin_session` is the only writer of the session
/// generation, and for a long time nothing invoked `start_session`, so the
/// coordinator sat at 0 while control stamped every stage payload with 1 and
/// every tracking snapshot was dropped. The generation is an OUTPUT: the input
/// struct has no field for it, and the value must advance per session.
#[test]
fn start_session_assigns_the_generation_control_must_adopt() {
    let h = harness();
    let created = h.expect_ok(
        "create_script",
        json!({ "input": { "title": "Take", "source": "# Take\n" } }),
    );
    let script_id = created["id"].as_str().unwrap().to_string();

    let input = json!({ "input": {
        "scriptId": script_id,
        "scriptSourceHash": "sha256:take",
        "mode": "voice",
        "startTokenIndex": 0,
    }});

    let first = h.expect_ok("start_session", input.clone());
    let g1 = first["sessionGeneration"].as_i64().expect("sessionGeneration");
    assert!(g1 >= 1, "a live session must not carry generation 0, got {g1}");

    h.expect_ok(
        "end_session",
        json!({ "sessionId": first["id"].as_str().unwrap(), "summary": null }),
    );

    let second = h.expect_ok("start_session", input);
    let g2 = second["sessionGeneration"].as_i64().unwrap();
    assert!(
        g2 > g1,
        "each take must get a fresh generation ({g1} → {g2}); a constant here is \
         precisely how a stale stage kept accepting payloads"
    );

    // Control must never propose a generation — there is no field to propose in.
    let echoed = h.expect_ok(
        "start_session",
        json!({ "input": {
            "scriptId": second["scriptId"].as_str().unwrap(),
            "scriptSourceHash": "sha256:take",
            "mode": "voice",
            "sessionGeneration": 99,
        }}),
    );
    assert_ne!(
        echoed["sessionGeneration"],
        json!(99),
        "the coordinator, not the webview, assigns the session generation"
    );
}

/// §36.2 — retention is decided by settings AT START and cannot be talked into
/// existence later. The settings patch the UI sends must be the one that flips
/// it, which is the mapping that was missing entirely.
#[test]
fn transcript_retention_follows_the_settings_patch_the_ui_sends() {
    let fixture = capture_fixture();
    let h = harness();
    let created = h.expect_ok(
        "create_script",
        json!({ "input": { "title": "Retention", "source": "# Retention\n" } }),
    );
    let script_id = created["id"].as_str().unwrap().to_string();

    let start = json!({ "input": {
        "scriptId": script_id,
        "scriptSourceHash": "sha256:retention",
        "mode": "voice",
    }});

    // Default is off.
    let before = h.expect_ok("start_session", start.clone());
    assert_eq!(
        before["transcriptRetained"],
        json!(false),
        "retention must default off (§36.2)"
    );
    h.expect_ok(
        "end_session",
        json!({ "sessionId": before["id"].as_str().unwrap(), "summary": null }),
    );

    // Apply the REAL captured patch from `updateSettings({ privacy: … })`.
    let settings = h.expect_ok("get_settings", Value::Null);
    let mut patch_args = fixture["invocations"]["update_settings"]["args"].clone();
    patch_args["expectedRevision"] = json!(settings["revision"].as_i64().unwrap());
    let updated = h.expect_ok("update_settings", patch_args);
    assert_eq!(
        updated["value"]["general"]["saveTranscript"],
        json!("7d"),
        "the UI's privacy patch must reach `general.saveTranscript`; without this \
         mapping the retention setting could not be changed at all"
    );

    let after = h.expect_ok("start_session", start);
    assert_eq!(
        after["transcriptRetained"],
        json!(true),
        "a session started after retention was enabled must retain"
    );

    // And the transcript really lands.
    let written = h.expect_ok(
        "append_session_transcript",
        json!({
            "sessionId": after["id"].as_str().unwrap(),
            "items": [{
                "commitSequence": 1,
                "transcript": "Good morning everyone.",
                "disposition": "script",
            }],
        }),
    );
    assert_eq!(written, json!(1));
}

