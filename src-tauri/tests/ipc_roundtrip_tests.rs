/// The C3/C7/S2/C5 class, at the boundary rather than at the DTO.
///
/// A domain error is fine here — `get_script` on an id that does not exist
/// SHOULD fail. What must never happen is Tauri refusing to bind the arguments
/// at all, because that failure is indistinguishable in the UI from "the
/// feature does nothing" and the mock backend hides it completely.
#[test]
fn every_captured_payload_binds_to_its_command() {
    let fixture = capture_fixture();
    let h = harness();
    let script_placeholder = placeholder(&fixture, "scriptId");
    let session_placeholder = placeholder(&fixture, "sessionId");

    // Real rows so the commands fail (if at all) for domain reasons only.
    let created = h.expect_ok(
        "create_script",
        json!({ "input": { "title": "Roundtrip", "source": "# Roundtrip\n\nBody.\n" } }),
    );
    let script_id = created["id"].as_str().expect("created id").to_string();
    let revision = created["scriptRevision"].as_i64().expect("created revision");

    let session = h.expect_ok(
        "start_session",
        json!({ "input": {
            "scriptId": script_id,
            "scriptSourceHash": "sha256:roundtrip",
            "mode": "voice",
        }}),
    );
    let session_id = session["id"].as_str().expect("session id").to_string();

    let mut checked = 0usize;
    for (name, command, args) in invocations(&fixture) {
        if !REPLAYED.contains(&command.as_str()) {
            continue;
        }
        let args = substitute(&args, &script_placeholder, &script_id);
        let args = substitute(&args, &session_placeholder, &session_id);
        let args = with_expected_revision(&args, revision);

        if let Err(error) = h.invoke(&command, args.clone()) {
            assert!(
                !is_argument_rejection(&error),
                "`{name}` sends a payload the `{command}` command cannot bind.\n  \
                 payload: {args}\n  error:   {error}\n  \
                 This is the C3/C5/S2 failure shape: the invoke is rejected before the \
                 command body runs, and in the app `invokeOrMock` would swallow it into \
                 the mock backend."
            );
        }
        checked += 1;
    }

    // Guard on the guard: a fixture that stopped listing anything, or a
    // REPLAYED list that no longer intersects it, must not read as a pass.
    assert!(
        checked >= 15,
        "only {checked} captured payloads were replayed; the fixture or the \
         REPLAYED list has gone stale"
    );
}

/// The specific shapes that broke, called out by name so a regression names
/// itself rather than appearing as one row in a loop.
#[test]
fn the_four_historical_argument_defects_are_rejections_today() {
    let h = harness();
    let created = h.expect_ok(
        "create_script",
        json!({ "input": { "title": "Historic", "source": "# Historic\n" } }),
    );
    let script_id = created["id"].as_str().unwrap().to_string();
    let revision = created["scriptRevision"].as_i64().unwrap();

    // C3 — `filter.view`, the field Rust never had. serde used to DROP it, so
    // the Trash view listed live scripts. It must now be a hard rejection.
    let err = h
        .invoke("list_scripts", json!({ "filter": { "view": "trash" } }))
        .expect_err("`view` is not a ScriptFilter field");
    assert!(
        is_argument_rejection(&err),
        "a `view` filter must be refused at the boundary, got: {err}"
    );

    // S2 — `page` as a bare number. The old TS signature sent one.
    let err = h
        .invoke("list_scripts", json!({ "page": 1 }))
        .expect_err("a bare page number is not a PageRequest");
    assert!(is_argument_rejection(&err), "got: {err}");

    // C5 — a required argument the caller has no way to supply. The shape is
    // the same one `export_all_data` had: send nothing for a non-Option
    // parameter and the invoke never reaches the command body.
    let err = h
        .invoke("rename_script", json!({ "scriptId": script_id, "expectedRevision": revision }))
        .expect_err("`title` is required");
    assert!(
        is_argument_rejection(&err),
        "a missing required argument must be an argument rejection, got: {err}"
    );

    // C7 — a sort key Rust does not implement must not silently become the
    // default ordering. (Rust accepts any string here, so this asserts the
    // POSITIVE half: the keys the library actually sends are implemented.)
    for sort in ["recently_edited", "name", "created", "estimated_length", "last_opened"] {
        h.expect_ok("list_scripts", json!({ "sort": sort }));
    }
}

