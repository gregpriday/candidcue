//! Layer 4 (spec §55.1), half two: replay the payloads the REAL TypeScript
//! services produce through the REAL Tauri command layer, against a REAL
//! database.
//!
//! What this covers that nothing else did
//! ---------------------------------------------------------------------------
//! `ipc_contract_tests.rs` deserializes a hand-written fixture into individual
//! DTOs. That catches a lot, but it stops one layer short of the boundary: it
//! never proves that Tauri's argument DISPATCH accepts the payload. Tauri maps
//! `{ "scriptId": … }` onto `script_id: String` by name; a renamed parameter, a
//! parameter that became non-optional, or an argument the service stopped
//! sending are all invisible to a `serde_json::from_value::<Dto>()` test and
//! all produce the same runtime symptom — `invalid args ... for command ...`,
//! a rejected invoke, and a feature that silently does nothing.
//!
//! And `src/control/services/mock-backend.ts` guarantees that symptom is
//! *quiet*: `invokeOrMock` falls through to an in-memory implementation that is
//! in places stronger than the Rust one, so a TypeScript test can watch the
//! Trash view work perfectly while the real command was never callable. This
//! file has no mock to fall through to.
//!
//! The payload source
//! ---------------------------------------------------------------------------
//! `tests/fixtures/ipc/captured-invocations.json` is GENERATED by
//! `tests/integration/ipc-payload-capture.test.ts`, which records what the
//! production service functions put on the wire. Nobody writes it by hand, so
//! it cannot describe a payload the frontend does not actually send.
//!
//! What is deliberately NOT replayed
//! ---------------------------------------------------------------------------
//!  - `import_script` / `export_script` / `export_all_data` / `import_image`:
//!    these open a native picker through `crate::dialogs`, which is written
//!    against `tauri::Wry` and cannot be registered on the `MockRuntime`. Their
//!    argument shapes are covered by `ipc_contract_tests.rs` instead.
//!  - the stage commands: they take `serde_json::Value` and so have no argument
//!    shape to drift. See `stage_payloads_have_no_typed_boundary_to_guard`.

